"""Generate the same native-command fixture for Forge 1.20.1 and NeoForge 1.21.1.

No /tick, fake outbound packets, foreign saves, or version-specific item NBT.
Run this script from any working directory to regenerate the checked-in scenario.
"""
from pathlib import Path

lines = ["# Generated by scripts/smoke/build-traffic-profile.py",
         "join label=WAIT_JOIN_1 since=start timeoutMs=${joinTimeoutMs} requirePositiveY=false",
         "wait ms=3000"]


def command(text):
    lines.append(f'command text="{text}"')


def wait(ms):
    lines.append(f"wait ms={ms}")


def window(name, mode=None):
    command(f"tag @s add traffic_{name}")
    lines.append(f"input mode={mode or 'idle'} ms=60000")
    command(f"tag @s remove traffic_{name}")
    # Empty tag interval separates windows and lets pending tick-end frames flush.
    wait(2000)


for text in [
    "gamerule sendCommandFeedback false", "gamerule doDaylightCycle false",
    "gamerule doWeatherCycle false", "gamerule doMobSpawning false",
    "gamerule randomTickSpeed 3", "time set noon", "weather clear",
    "gamemode creative", "tp @s 0.5 140 0.5 0 10",
    "fill -48 139 -48 55 139 48 stone",
    "fill -24 140 -24 24 144 24 air",
    "fill 22 140 10 50 146 36 air",
    # Identical naturally ticking animals in a pen, present for all samples.
    "fill -23 140 6 -5 141 26 glass hollow",
    "fill -22 140 7 -6 141 25 air",
]:
    command(text)
for i in range(24):
    command(f"summon pig {-21 + (i % 6) * 2}.5 140 {9 + (i // 6) * 3}.5")
wait(60000)
for i in range(1, 4):
    command("tp @s 0.5 140 0.5 0 10")
    wait(5000)
    window(f"normal_r{i}", "walk")
command("tp @s 0.5 140 0.5 90 10")
wait(15000)
for i in range(1, 4):
    window(f"observe_r{i}")

# 16 genuine observer clocks. Each powers a sticky piston and a dropper.
# The dropper ejects into air, so vanilla ItemEntities fall into a hopper/chest.
# Supply chests feed the droppers through hoppers; no refill injection during samples.
for i in range(16):
    x, z = 24 + (i % 4) * 7, 12 + (i // 4) * 7
    for text in [
        f"setblock {x-1} 142 {z} sticky_piston[facing=up]",
        f"setblock {x-1} 143 {z} stone",
        f"setblock {x} 142 {z} observer[facing=east]",
        f"setblock {x+2} 139 {z} chest",
        f"setblock {x+2} 140 {z} hopper[facing=down]",
        f"setblock {x+2} 142 {z} dropper[facing=down]",
        f"setblock {x+2} 143 {z} hopper[facing=down]",
        f"setblock {x+2} 144 {z} chest",
    ]:
        command(text)
    # Full supply chest keeps the 5-minute input comparison from running out of fuel.
    for slot in range(27):
        if slot < 9:
            command(f"item replace block {x+2} 142 {z} container.{slot} with cobblestone 64")
        command(f"item replace block {x+2} 144 {z} container.{slot} with cobblestone 64")
    # Throttle command submission; also keeps the setup transport out of sampling.
    wait(250)
for i in range(16):
    x, z = 24 + (i % 4) * 7, 12 + (i // 4) * 7
    command(f"setblock {x+1} 142 {z} observer[facing=west]")
command("tp @s 30.5 140 5.5 0 20")
command("gamemode survival")
wait(45000)
for i in range(1, 4):
    window(f"factory_r{i}")
# Stable position/camera with attack input: this is still a potential AFK case.
# Unbreakable target avoids altering the fixture or teleporting the player.
command("setblock 30 139 5 bedrock")
command("tp @s 30.5 140 5.5 0 90")
wait(10000)
window("factory_hold", "hold_attack")
window("factory_periodic", "periodic_attack")
command("tag @s add traffic_done")
lines += ["assertProbe key=joined op=eq value=true", "dump label=ROUND1 round=1",
          "exit rounds=1"]
path = Path(__file__).resolve().parents[2] / "common/src/main/resources/hassium/smoke/scenario/trafficprofile.scenario"
path.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(lines)} steps to {path}")
